import { ContainerInfo, execReadonly, getContainerLogs } from './docker_service';

export interface ControlServerStatus {
    /** Whether GLUETUN_CONTROL_URL is set at all. */
    configured: boolean;
    /** An HTTP response came back (any status). */
    reachable: boolean;
    /** null until a request answers; false on 401/403. */
    authorised: boolean | null;
    /** Gluetun's own VPN loop state: running, stopped, crashed... */
    vpnStatus: string;
    dnsStatus: string;
    detail: string;
}

export interface VpnStatus {
    containerPresent: boolean;
    containerRunning: boolean;
    containerHealthy: boolean | null;
    tunnelUp: boolean | null;
    publicIp: string | null;
    /** Where the exit IP came from, so a lookup failure is not read as a tunnel failure. */
    publicIpSource: string;
    location: string;
    org: string;
    provider: string;
    protocol: string;
    serverFilter: string;
    forwardedPort: number | null;
    uptimeSeconds: number | null;
    restartCount: number;
    dnsOk: boolean | null;
    httpsOk: boolean | null;
    control: ControlServerStatus;
    authFailures: number;
    reconnects: number;
    recentErrors: string[];
    recommendation: string;
    error: string;
    checkedAt: number;
    source: string;
}

export interface LeakCheck {
    passed: boolean | null;
    vpnIp: string | null;
    wanIp: string | null;
    detail: string;
    conclusive: boolean;
}

// First match wins, so specific configuration faults come before the symptoms
// they cause (a bad key also produces TLS errors and a restart loop).
const LOG_SIGNATURES: Array<[RegExp, string, string]> = [
    [
        /AUTH_FAILED/i,
        "VPN authentication failure",
        "The provider rejected the credentials. Check OPENVPN_USER/OPENVPN_PASSWORD in the Gluetun environment — providers issue separate OpenVPN credentials, not the account login."
    ],
    [
        /TUN device is not available|\/dev\/net\/tun/i,
        "TUN device unavailable to Gluetun",
        "Give the gluetun service `devices: [/dev/net/tun:/dev/net/tun]` and `cap_add: [NET_ADMIN]`, then recreate it."
    ],
    [
        /operation not permitted.*(iptables|netlink|route)|(iptables|netlink).*operation not permitted/i,
        "Gluetun lacks the NET_ADMIN capability",
        "Add `cap_add: [NET_ADMIN]` to the gluetun service and recreate it."
    ],
    [
        /private key is not set|WIREGUARD_PRIVATE_KEY|wireguard.*(key|address).*(invalid|missing|not set)/i,
        "WireGuard key or address missing or invalid",
        "WIREGUARD_PRIVATE_KEY and WIREGUARD_ADDRESSES must both come from one WireGuard config generated by the provider (ProtonVPN: Account → WireGuard). A regenerated or revoked config invalidates the old key."
    ],
    [
        /no server found|no server matching|no server available/i,
        "No VPN server matches the configured filters",
        "Relax SERVER_COUNTRIES / SERVER_CITIES / SERVER_HOSTNAMES, or let Gluetun refresh its server list (UPDATER_PERIOD=24h)."
    ],
    [
        /address already in use/i,
        "A published port is already taken on the host",
        "Another process holds one of Gluetun's published ports. `ss -ltnp` shows which."
    ],
    [
        /TLS Error|TLS handshake failed/i,
        "TLS handshake failure to the VPN endpoint",
        "The endpoint may be down or blocked. Try a different server."
    ],
    [
        /Connection refused|Network is unreachable/i,
        "Network path to the VPN endpoint unavailable",
        "Check the host's own Internet connectivity first."
    ],
    [
        /dial tcp.*i\/o timeout/i,
        "Timeout reaching the VPN endpoint",
        "Provider-side or upstream network issue."
    ],
    [
        /\[dns\].*\b(error|failed)\b/i,
        "DNS inside Gluetun is failing",
        "Gluetun's DNS-over-TLS cannot reach its upstream. Test with DOT=off; if that fixes it, outbound port 853 is being blocked."
    ],
    [
        /program has been unhealthy|healthcheck.*unhealthy/i,
        "Gluetun's internal healthcheck is failing",
        "The tunnel connects but traffic is not flowing. Gluetun restarts the VPN itself; if it keeps cycling, pin a different server."
    ],
    [
        /did not run yet/i,
        "Gluetun health server has not completed its first check",
        "Normal briefly after a restart; persistent means the tunnel never came up."
    ],
    [
        /SIGUSR1|restarting/i,
        "Tunnel restart loop",
        "Gluetun is cycling. Read the lines above the restart for the trigger."
    ],
];

export function analyseLogs(lines: string[]): { cause: string; recommendation: string; authFailures: number; reconnects: number; errors: string[] } {
    const authFailures = lines.filter(line => line.toUpperCase().includes("AUTH_FAILED")).length;
    const reconnects = lines.filter(line => /SIGUSR1|restarting|reconnect/i.test(line)).length;
    const errors = lines.filter(line => /\bERROR\b|\bFATAL\b|AUTH_FAILED|TLS Error/i.test(line)).slice(-8);

    for (const [pattern, cause, recommendation] of LOG_SIGNATURES) {
        if (lines.some(line => pattern.test(line))) {
            return { cause, recommendation, authFailures, reconnects, errors };
        }
    }
    return { cause: "", recommendation: "", authFailures, reconnects, errors };
}

/** Docker exec's exit status when the program is missing from the image. */
function commandMissing(code: number): boolean {
    return code === 126 || code === 127;
}

/**
 * Decide the tunnel state from whatever evidence was gathered. Gluetun's
 * firewall is a kill switch, so outbound HTTPS from inside its namespace only
 * works while the tunnel is up — a failed exit-IP lookup (rate limited,
 * service down) is therefore not by itself evidence the tunnel is down.
 */
export function inferTunnelUp(evidence: {
    controlVpnStatus: string;
    publicIp: string | null;
    httpsOk: boolean | null;
}): boolean | null {
    if (evidence.controlVpnStatus) {
        return evidence.controlVpnStatus === "running";
    }
    if (evidence.publicIp) return true;
    return evidence.httpsOk;
}

export function describeServerFilter(env: Record<string, string>): string {
    return ["SERVER_HOSTNAMES", "SERVER_CITIES", "SERVER_REGIONS", "SERVER_COUNTRIES", "SERVER_CATEGORIES"]
        .filter(key => env[key])
        .map(key => `${key.substring("SERVER_".length).toLowerCase()}: ${env[key]}`)
        .join(" · ");
}

export async function getVpnStatus(
    container: ContainerInfo | null,
    containerName: string,
    options: {
        ipCheckUrl?: string;
        provider?: string;
        protocol?: string;
        controlUrl?: string;
        apiKey?: string | null;
        timeout?: number;
        readLogs?: boolean;
    } = {}
): Promise<VpnStatus> {
    const ipCheckUrl = options.ipCheckUrl || "https://ipinfo.io/json";
    const controlUrl = options.controlUrl || "";
    const apiKey = options.apiKey || null;
    const timeout = options.timeout || 10.0;
    const readLogs = options.readLogs !== false;

    const status: VpnStatus = {
        containerPresent: false,
        containerRunning: false,
        containerHealthy: null,
        tunnelUp: null,
        publicIp: null,
        publicIpSource: "",
        location: "",
        org: "",
        provider: options.provider || "protonvpn",
        protocol: options.protocol || "wireguard",
        serverFilter: "",
        forwardedPort: null,
        uptimeSeconds: null,
        restartCount: 0,
        dnsOk: null,
        httpsOk: null,
        control: {
            configured: Boolean(controlUrl),
            reachable: false,
            authorised: null,
            vpnStatus: "",
            dnsStatus: "",
            detail: controlUrl ? "" : "GLUETUN_CONTROL_URL is not set; tunnel state is inferred from inside the container.",
        },
        authFailures: 0,
        reconnects: 0,
        recentErrors: [],
        recommendation: "",
        error: "",
        checkedAt: Date.now() / 1000,
        source: "docker"
    };

    if (!container) {
        status.error = `Container ${containerName} not found`;
        return status;
    }

    status.containerPresent = true;
    status.containerRunning = container.running;
    status.containerHealthy = container.healthy;
    status.uptimeSeconds = container.uptime_seconds;
    status.restartCount = container.restart_count;

    // What the container is actually configured with beats what the dashboard
    // was told: a stack switched to WireGuard keeps whatever VPN_PROTOCOL says here.
    const env = container.public_env ?? {};
    if (env.VPN_SERVICE_PROVIDER) status.provider = env.VPN_SERVICE_PROVIDER;
    if (env.VPN_TYPE) status.protocol = env.VPN_TYPE;
    status.serverFilter = describeServerFilter(env);

    if (!container.running) {
        status.tunnelUp = false;
        status.error = `Container state: ${container.state}`;
        if (readLogs) {
            await attachLogAnalysis(status, containerName);
        }
        return status;
    }

    if (controlUrl) {
        await augmentFromControlServer(status, controlUrl, apiKey, timeout);
        if (status.control.authorised) {
            status.source = "gluetun control server + docker";
        }
    }

    if (!status.publicIp) {
        const ipInfo = await exitIpViaContainer(containerName, ipCheckUrl, timeout);
        if (ipInfo) {
            applyIpInfo(status, ipInfo, "docker exec");
        }
    }

    if (status.publicIp) {
        status.dnsOk = true;
        status.httpsOk = true;
    } else {
        const probes = await probeFromContainer(containerName, timeout);
        status.dnsOk = probes.dnsOk;
        status.httpsOk = probes.httpsOk;
    }

    status.tunnelUp = inferTunnelUp({
        controlVpnStatus: status.control.vpnStatus,
        publicIp: status.publicIp,
        httpsOk: status.httpsOk,
    });

    const unhealthy = status.containerHealthy === false || status.tunnelUp === false || status.dnsOk === false;
    if (readLogs && unhealthy) {
        await attachLogAnalysis(status, containerName);
    }

    return status;
}

function applyIpInfo(status: VpnStatus, info: Record<string, any>, source: string): void {
    const ip = info.ip || info.public_ip;
    if (!ip) return;
    status.publicIp = String(ip);
    status.publicIpSource = source;
    const locationParts = [info.city, info.region, info.country].filter(Boolean);
    if (locationParts.length > 0) status.location = locationParts.join(", ");
    const org = info.org || info.organization;
    if (org) status.org = String(org);
}

const exitIpCache = new Map<string, { data: Record<string, any>; expiresAt: number }>();

// Tried after the configured URL. ipinfo answers with location data but
// rate-limits shared VPN exit addresses hard, so plain-text services back it up.
const FALLBACK_IP_URLS = ["https://api.ipify.org", "https://icanhazip.com"];

async function exitIpViaContainer(containerName: string, url: string, timeoutSec: number): Promise<Record<string, any> | null> {
    const now = Date.now();
    const cacheKey = `${containerName}|${url}`;
    const cached = exitIpCache.get(cacheKey);

    if (cached && cached.expiresAt > now) {
        return cached.data;
    }

    for (const target of [url, ...FALLBACK_IP_URLS.filter(u => u !== url)]) {
        // Gluetun's image ships busybox wget; curl covers other images.
        for (const argv of [["wget", "-qO-", "-T", "8", target], ["curl", "-s", "-m", "8", target]]) {
            try {
                const { code, output } = await execReadonly(containerName, argv, timeoutSec);
                if (commandMissing(code)) continue;
                if (code !== 0 || !output) break;

                let result: Record<string, any> | null = null;
                try {
                    const payload = JSON.parse(output);
                    if (payload && typeof payload === 'object' && payload.ip) {
                        result = payload;
                    }
                } catch (e) {
                    const candidate = output.trim();
                    if (/^[0-9a-fA-F.:]+$/.test(candidate)) {
                        result = { ip: candidate };
                    }
                }
                if (result) {
                    exitIpCache.set(cacheKey, { data: result, expiresAt: now + 90000 });
                    return result;
                }
                break;
            } catch (exc) {
                console.debug(`exec ${argv[0]} failed:`, exc);
            }
        }
    }
    return null;
}

async function probeFromContainer(containerName: string, timeoutSec: number): Promise<{ dnsOk: boolean | null, httpsOk: boolean | null }> {
    let dnsOk: boolean | null = null;
    let httpsOk: boolean | null = null;

    try {
        const { code } = await execReadonly(containerName, ["nslookup", "cloudflare.com"], timeoutSec);
        dnsOk = commandMissing(code) ? null : code === 0;
    } catch (e) {
        dnsOk = null;
    }

    try {
        const { code } = await execReadonly(containerName, ["wget", "-q", "--spider", "-T", "6", "https://1.1.1.1"], timeoutSec);
        httpsOk = commandMissing(code) ? null : code === 0;
    } catch (e) {
        httpsOk = null;
    }

    return { dnsOk, httpsOk };
}

async function controlGet(base: string, route: string, apiKey: string | null, timeoutSec: number): Promise<{ httpStatus: number; body: any } | null> {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), timeoutSec * 1000);
    try {
        const response = await fetch(`${base}${route}`, {
            headers: apiKey ? { "X-API-Key": apiKey } : {},
            redirect: "manual",
            signal: controller.signal,
        });
        let body: any = null;
        try {
            body = await response.json();
        } catch {
            body = null;
        }
        return { httpStatus: response.status, body };
    } catch (exc) {
        console.debug(`Gluetun control server ${route} unavailable:`, exc);
        return null;
    } finally {
        clearTimeout(timeoutId);
    }
}

/**
 * Read Gluetun's HTTP control server: /v1/vpn/status, /v1/publicip/ip,
 * /v1/portforward and /v1/dns/status. The older /v1/openvpn/* routes are gone
 * from current releases and only ever described OpenVPN, which made a healthy
 * WireGuard tunnel look stopped.
 */
async function augmentFromControlServer(status: VpnStatus, controlUrl: string, apiKey: string | null, timeoutSec: number): Promise<void> {
    const base = controlUrl.replace(/\/$/, "");
    const control = status.control;

    const vpnState = await controlGet(base, "/v1/vpn/status", apiKey, timeoutSec);
    if (!vpnState) {
        control.detail = `No answer from ${base}. Check that the gluetun container publishes port 8000 and HTTP_CONTROL_SERVER_ADDRESS is :8000.`;
        return;
    }
    control.reachable = true;

    if (vpnState.httpStatus === 401 || vpnState.httpStatus === 403) {
        control.authorised = false;
        control.detail = apiKey
            ? "Gluetun rejected GLUETUN_API_KEY. It must match the apikey in Gluetun's auth config (/gluetun/auth/config.toml) or HTTP_CONTROL_SERVER_AUTH_DEFAULT_ROLE."
            : "Gluetun's control server requires authentication. Generate a key with `docker run --rm qmcgaw/gluetun genkey`, give Gluetun an apikey role covering GET /v1/vpn/status, /v1/publicip/ip, /v1/portforward and /v1/dns/status, and set GLUETUN_API_KEY here.";
        return;
    }
    if (vpnState.httpStatus !== 200) {
        control.detail = `GET /v1/vpn/status returned HTTP ${vpnState.httpStatus}; this Gluetun release may be too old for the current control API.`;
        return;
    }
    control.authorised = true;
    control.vpnStatus = String(vpnState.body?.status || "").toLowerCase();

    const [publicIp, forwarded, dns] = await Promise.all([
        controlGet(base, "/v1/publicip/ip", apiKey, timeoutSec),
        controlGet(base, "/v1/portforward", apiKey, timeoutSec),
        controlGet(base, "/v1/dns/status", apiKey, timeoutSec),
    ]);

    if (publicIp?.httpStatus === 200 && publicIp.body) {
        applyIpInfo(status, publicIp.body, "gluetun control server");
    }
    if (forwarded?.httpStatus === 200 && forwarded.body?.port) {
        status.forwardedPort = Number(forwarded.body.port) || null;
    }
    if (dns?.httpStatus === 200 && dns.body?.status) {
        control.dnsStatus = String(dns.body.status).toLowerCase();
    }
    control.detail = `VPN ${control.vpnStatus || "unknown"}${control.dnsStatus ? `, DNS ${control.dnsStatus}` : ""}.`;
}

async function attachLogAnalysis(status: VpnStatus, containerName: string): Promise<void> {
    let lines: string[];
    try {
        lines = await getContainerLogs(containerName, 200);
    } catch (e) {
        return; // E.g., DockerUnavailable equivalent
    }

    if (!lines || lines.length === 0) return;

    const { cause, recommendation, authFailures, reconnects, errors } = analyseLogs(lines);
    status.authFailures = authFailures;
    status.reconnects = reconnects;
    status.recentErrors = errors;

    if (cause) {
        status.error = cause;
        status.recommendation = recommendation;
    }
}

export function checkLeak(vpnIp: string | null, wanIp: string | null): LeakCheck {
    if (!vpnIp && !wanIp) {
        return {
            passed: null,
            vpnIp: null,
            wanIp: null,
            detail: "Neither the VPN exit IP nor the home WAN IP could be determined.",
            conclusive: false
        };
    }
    if (!vpnIp) {
        return {
            passed: null,
            vpnIp: null,
            wanIp: wanIp,
            detail: "VPN exit IP unknown — the tunnel may be down. Cannot confirm that download traffic is leaving through the VPN.",
            conclusive: false
        };
    }
    if (!wanIp) {
        return {
            passed: null,
            vpnIp: vpnIp,
            wanIp: null,
            detail: "Home WAN IP unknown, so the comparison cannot be made. Check outbound HTTPS from the host.",
            conclusive: false
        };
    }
    if (vpnIp === wanIp) {
        return {
            passed: false,
            vpnIp: vpnIp,
            wanIp: wanIp,
            detail: "The download stack's public IP matches the home WAN IP. Traffic is not going through the VPN.",
            conclusive: true
        };
    }
    return {
        passed: true,
        vpnIp: vpnIp,
        wanIp: wanIp,
        detail: "Download stack exits on a different public IP from the home WAN.",
        conclusive: true
    };
}
